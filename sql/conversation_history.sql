-- Persistent chat history for the AI mentor.
-- Run with the Supabase service-role/admin SQL editor.
create table if not exists public.conversation_history (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public."Students"(id) on delete cascade,
    role text not null check (role in ('student','bot')),
    content text not null,
    created_at timestamptz not null default now()
);
create index if not exists conversation_history_student_created_idx
    on public.conversation_history(student_id, created_at desc);
alter table public.conversation_history enable row level security;
revoke all on public.conversation_history from anon, authenticated;
