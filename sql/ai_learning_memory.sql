-- Durable memory for the natural AI mentor.
-- Run once in Supabase SQL Editor with the backend service role.
create table if not exists public.ai_learning_memory (
    id bigint generated by default as identity primary key,
    student_id bigint not null unique references public."Students"(id) on delete cascade,
    recurring_mistakes jsonb not null default '[]'::jsonb,
    topics_to_review jsonb not null default '[]'::jsonb,
    weak_areas jsonb not null default '[]'::jsonb,
    learning_plan jsonb not null default '[]'::jsonb,
    last_summary text not null default '',
    updated_at timestamptz not null default now()
);
create index if not exists ai_learning_memory_student_idx
    on public.ai_learning_memory(student_id);
alter table public.ai_learning_memory enable row level security;
revoke all on public.ai_learning_memory from anon, authenticated;
