create table if not exists public.learning_session_results (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id),
 topic text, block text, kind text not null default 'exercise',
 score integer not null, total integer not null check (total > 0),
 created_at timestamptz not null default now()
);
alter table public.learning_session_results enable row level security;
