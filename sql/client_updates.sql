-- Run once in Supabase SQL Editor for completed lesson/test history.
create table if not exists public.learning_session_results (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id) on delete cascade,
 topic text not null,
 block text not null,
 kind text not null default 'exercise',
 score integer not null,
 total integer not null check (total > 0),
 created_at timestamptz not null default now()
);
alter table public.learning_session_results enable row level security;
create index if not exists learning_session_student_idx on public.learning_session_results(student_id, created_at);

-- Stripe customer/session mapping. Backend service-role access only.
create table if not exists public.stripe_payment_profiles (
 student_id bigint primary key references public."Students"(id) on delete cascade,
 customer_id text,
 subscription_id text unique,
 checkout_session_id text,
 checkout_request_id text,
 status text,
 current_period_end timestamptz,
 last_payment_id text,
 last_paid_at timestamptz
);
alter table public.stripe_payment_profiles enable row level security;
alter table public.stripe_payment_profiles add column if not exists current_period_end timestamptz;
alter table public.stripe_payment_profiles add column if not exists last_payment_id text;
alter table public.stripe_payment_profiles add column if not exists last_paid_at timestamptz;

-- AI mentor billing memory: lets the mentor distinguish current access from the previous state.
alter table public.stripe_payment_profiles add column if not exists previous_status text;
alter table public.stripe_payment_profiles add column if not exists status_changed_at timestamptz;

-- Live AI conversation activity used by the dashboard.
create table if not exists public.learning_activity (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id) on delete cascade,
 event_type text not null,
 block text,
 topic text,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index if not exists learning_activity_student_created_idx on public.learning_activity(student_id, created_at desc);
alter table public.learning_activity enable row level security;
revoke all on public.learning_activity from anon, authenticated;
