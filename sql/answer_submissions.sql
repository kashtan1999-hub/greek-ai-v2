-- Durable raw answers before AI grading; no changes to existing Exercises.
create table if not exists public.answer_submissions (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id) on delete cascade,
 exercise_id bigint, question text not null, user_answer text not null,
 block text, topic text, status text not null default 'pending', result text,
 created_at timestamptz not null default now()
);
alter table public.answer_submissions enable row level security;
