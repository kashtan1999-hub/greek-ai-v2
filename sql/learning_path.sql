-- Atomic reset of one learner, never payment/profile/curriculum data.
create or replace function public.reset_learning_history(p_student_id bigint, p_block text, p_topic text)
returns void language plpgsql security invoker set search_path = public as $$
declare t text;
begin
 foreach t in array array['attempts','learning_errors','learning_session_results','learning_history','learning_paths','learning_plans','voice_practice_attempts','answer_submissions'] loop
  if to_regclass('public.' || t) is not null then
   execute format('delete from public.%I where student_id = $1', t) using p_student_id;
  end if;
 end loop;
 update public.student_state set current_block=p_block, current_topic=p_topic,
 current_step=1, interaction_number=1, active_plan=null, next_action='continue_learning',
 weak_topics=default, total_score=0, completed_questions=0, total_questions=0,
 exercise_progress=0, block_progress=0, lesson_progress=0,
 updated_at=now(), last_activity_at=now() where student_id=p_student_id;
end; $$;
revoke all on function public.reset_learning_history(bigint,text,text) from public, anon, authenticated;
grant execute on function public.reset_learning_history(bigint,text,text) to service_role;
