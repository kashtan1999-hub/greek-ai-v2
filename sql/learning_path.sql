alter table public."Exercises" add column if not exists topic text;
create table if not exists public.learner_profiles (
 student_id bigint primary key references public."Students"(id) on delete cascade,
 introduction text not null default '', completed boolean not null default false
);
create table if not exists public.learning_history (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id) on delete cascade,
 block text not null, topic text not null, completed text not null,
 stopped_at text not null, score integer, mistakes jsonb not null default '[]',
 study_plan text not null, next_material jsonb, review_due_at timestamptz,
 created_at timestamptz not null default now()
);
create table if not exists public.learning_paths (
 id bigint generated by default as identity primary key,
 student_id bigint not null references public."Students"(id) on delete cascade,
 block text not null, topic text not null, stage integer not null default 0,
 retained boolean not null default false, review_due_at timestamptz not null,
 unique(student_id, block, topic)
);
