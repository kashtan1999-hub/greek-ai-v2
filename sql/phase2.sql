-- Voice-practice history. Run this addition once in Supabase.
create table if not exists public.voice_practice_attempts (
    id bigint generated by default as identity not null,
    student_id bigint not null,
    block text not null,
    topic text not null,
    transcription text not null,
    feedback text not null,
    created_at timestamp with time zone not null default now(),
    constraint voice_practice_attempts_pkey primary key (id),
    constraint voice_practice_attempts_student_id_fkey
        foreign key (student_id) references public."Students"(id) on delete cascade
);

create index if not exists voice_practice_student_created_idx
on public.voice_practice_attempts (student_id, created_at desc);

alter table public.voice_practice_attempts enable row level security;
