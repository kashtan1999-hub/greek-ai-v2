-- Greek Tutor: live AI/activity events for dashboard and learning continuity.
-- Run once in Supabase SQL Editor. Backend uses the service-role key.
create table if not exists public.learning_activity (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public."Students"(id) on delete cascade,
    event_type text not null,
    block text,
    topic text,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists learning_activity_student_created_idx
    on public.learning_activity(student_id, created_at desc);
alter table public.learning_activity enable row level security;
revoke all on public.learning_activity from anon, authenticated;
