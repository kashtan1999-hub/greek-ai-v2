AI_EXERCISE_CACHE: dict[Any, dict] = {}

DEFAULT_EXERCISE_TOTAL = 10
DEFAULT_DATABASE_MAIN = 5


def _exercise_total() -> int:
    try:
        value = int(os.getenv("EXERCISE_TOTAL", DEFAULT_EXERCISE_TOTAL))
        return max(5, min(value, 20))
    except ValueError:
        return DEFAULT_EXERCISE_TOTAL


def normalize_answer(value: str) -> str:
    """Normalize only for display/debugging; production grading is AI semantic grading."""
    value = str(value or "").casefold().strip()
    value = re.sub(
        r"[^\w\sάέήίόύώϊΐϋΰα-ω]",
        "",
        value,
        flags=re.UNICODE,
    )
    return re.sub(r"\s+", " ", value)


def get_exercise(exercise_id):
    if exercise_id in AI_EXERCISE_CACHE:
        return AI_EXERCISE_CACHE[exercise_id]

    response = (
        supabase.table("Exercises")
        .select("*")
        .eq("id", exercise_id)
        .limit(1)
        .execute()
    )
    exercise = response.data[0] if response.data else None
    if exercise:
        AI_EXERCISE_CACHE[exercise_id] = exercise
    return exercise


def list_exercises(block: str, topic: str | None = None):
    """Return stored exercises for a block.

    The current Exercises schema does not contain a topic column, so topic is
    intentionally not used in the Supabase filter. The current curriculum
    block is the stable link between the lesson and its stored exercises.
    """
    query = (
        supabase.table("Exercises")
        .select("*")
        .eq("block", block)
        .order("id")
    )
    if topic:
        first = get_lesson(block)
        if first and topic == first.get('topic'):
            # Legacy untagged questions belong only to the first topic in a block.
            rows = [r for r in (query.execute().data or []) if not str(r.get('question','')).startswith('[Практика ошибок]')]
            return [row for row in rows if not row.get('topic') or row.get('topic') == topic]
        query = query.eq('topic', topic)
    return [r for r in (query.execute().data or []) if not str(r.get('question','')).startswith('[Практика ошибок]')]


def _format_generated_question(item: dict) -> str:
    """Persist multiple-choice options inside the existing question column.

    This keeps the existing Supabase schema unchanged while still allowing
    Telegram to render clickable options.
    """
    question = str(item.get("question") or "").strip()
    exercise_type = str(item.get("type") or "practice").strip().lower()
    options = item.get("options") or []

    if exercise_type != "multiple_choice" or not options:
        return question

    # Avoid duplicating options if a model already included them in the question.
    if re.search(r"\boptions\s*:", question, flags=re.IGNORECASE):
        return question

    letters = "ABCD"
    option_lines = [
        f"{letters[index]}) {str(option).strip()}"
        for index, option in enumerate(options[:4])
        if str(option).strip()
    ]
    return f"{question}\n\nOptions:\n" + "\n".join(option_lines)


async def ensure_exercises(block: str, topic: str):
    """Use database questions first, then generate additional questions.

    The session target is 10 questions by default:
    - stored database questions are kept as the main questions;
    - missing questions are generated by OpenAI from the current lesson;
    - generated questions are saved back to Exercises;
    - subsequent sessions reuse the stored set instead of generating duplicates.
    """
    total_needed = _exercise_total()
    lesson = get_lesson(block, topic) or get_lesson(block)

    if not lesson:
        raise ValueError(
            f"No curriculum content found for {block} / {topic}"
        )

    content = str(lesson.get("content") or "").strip()
    if not content:
        raise ValueError(
            f"Curriculum lesson is empty for {block} / {topic}"
        )

    existing = list_exercises(block, topic)

    # Keep the existing database questions as the first/main part of the test.
    # Use every stored question up to the session target; this avoids discarding
    # valid database questions when more than the configured main-question count
    # already exists.
    main_questions = existing[:total_needed]

    # If a previous run has already built the full stored set, reuse it.
    if len(existing) >= total_needed:
        selected = existing[:total_needed]
        for exercise in selected:
            AI_EXERCISE_CACHE[exercise["id"]] = exercise
        return selected

    # Otherwise generate only the missing number of questions.
    additional_needed = total_needed - len(main_questions)
    generated = await generate_exercises(
        block=block,
        topic=topic,
        lesson=content,
        amount=additional_needed,
        existing_exercises=main_questions,
    )

    if len(generated) != additional_needed:
        raise RuntimeError(
            f"AI returned {len(generated)} additional exercises; "
            f"{additional_needed} are required."
        )

    exercises = list(main_questions)
    existing_questions = {
        re.sub(r"\s+", " ", str(row.get("question") or "").casefold())
        for row in existing
    }

    for item in generated:
        question = _format_generated_question(item)
        answer = str(item.get("correct_answer") or "").strip()
        exercise_type = str(item.get("type") or "practice").strip().lower()

        if not question or not answer:
            raise ValueError(
                "AI returned an exercise with an empty question or answer."
            )

        dedupe_key = re.sub(r"\s+", " ", question.casefold())
        if dedupe_key in existing_questions:
            raise RuntimeError(
                "AI generated a duplicate exercise. Please retry this exercise set."
            )

        payload = {
            "block": block,
            "topic": topic,
            "exercise_type": exercise_type,
            "question": question,
            "correct_answer": answer,
        }

        saved = (
            supabase.table("Exercises")
            .insert(payload)
            .execute()
        )

        if not saved.data:
            raise RuntimeError(
                "Supabase did not return the saved exercise."
            )

        exercise = saved.data[0]
        AI_EXERCISE_CACHE[exercise["id"]] = exercise
        exercises.append(exercise)
        existing_questions.add(dedupe_key)

    if len(exercises) != total_needed:
        raise RuntimeError(
            "Exercise session was not created with the required number of exercises."
        )

    return exercises


async def evaluate(exercise: dict, student_answer: str):
    """AI-only semantic grading."""
    answer = str(student_answer or "").strip()
    if not answer:
        return {
            "result": "incorrect",
            "score": 0,
            "feedback": "Please provide an answer.",
        }

    from services.keyboard_answers import equivalent_letter, equivalent_boolean
    if equivalent_letter(exercise, answer) or equivalent_boolean(exercise, answer):
        return {'result': 'correct', 'score': 1, 'feedback': 'Верно! Принят тот же символ с другой клавиатуры.'}

    print("\n========== EXERCISE AI CHECK START ==========")
    print("QUESTION:", exercise.get("question"))
    print("EXPECTED:", exercise.get("correct_answer"))
    print("STUDENT:", answer)

    result = await grade_answer(
        question=str(exercise.get("question") or ""),
        correct_answer=str(exercise.get("correct_answer") or ""),
        student_answer=answer,
        lesson=lesson_context(
            str(exercise.get("block") or ""),
            None,
        ),
    )

    if result.get("result") not in {"correct", "incorrect"}:
        raise RuntimeError(
            f"Invalid AI grading result: {result!r}"
        )

    result["score"] = 1 if result["result"] == "correct" else 0

    print("AI GRADER RESULT:", result)
    print("========== EXERCISE AI CHECK END ==========\n")
    return result


def save_attempt(
    student_id: int,
    exercise: dict,
    student_answer: str,
    grade: dict,
    hint_used: bool,
    topic: str | None = None,
):
    """Persist an attempt using the existing attempts table schema."""
    result = str(grade.get("result") or "incorrect")
    score = 1 if result == "correct" else 0
    topic_value = str(
        topic
        or exercise.get("topic")
        or "General Practice"
    ).strip()

    inserted = (
        supabase.table("attempts")
        .insert(
            {
                "student_id": student_id,
                "topic": topic_value,
                "question": exercise["question"],
                "user_answer": student_answer,
                "result": result,
                "score": score,
                "hint_used": bool(hint_used),
                "created_at": utc_now(),
            }
        )
        .execute()
    )

    if not inserted.data:
        raise RuntimeError(
            "Attempt was not saved to Supabase."
        )

    state = get_student_state(student_id)
    if state:
        completed = int(state.get("completed_questions") or 0) + 1
        old_total_score = int(state.get("total_score") or 0)
        total_score = old_total_score + score
        total_questions = max(
            int(state.get("total_questions") or 0),
            completed,
        )
        exercise_progress = (
            round((total_score / total_questions) * 100)
            if total_questions
            else 0
        )

        update_state(
            student_id,
            {
                "total_score": total_score,
                "completed_questions": completed,
                "total_questions": total_questions,
                "exercise_progress": exercise_progress,
                "last_action": (
                    "correct_answer"
                    if score
                    else "incorrect_answer"
                ),
            },
        )
        increase_interaction(student_id, state)


def save_learning_error(
    student_id: int,
    exercise: dict,
    student_answer: str,
    topic: str | None = None,
):
    """Upsert the student's latest unresolved mistake."""
    topic_value = str(
        topic
        or exercise.get("topic")
        or "General Practice"
    ).strip()

    existing = (
        supabase.table("learning_errors")
        .select("id,count")
        .eq("student_id", student_id)
        .eq("topic", topic_value)
        .eq("exercise_id", exercise["id"])
        .eq("resolved", False)
        .limit(1)
        .execute()
    )

    payload = {
        "question": exercise["question"],
        "exercise_id": exercise["id"],
        "wrong_answer": student_answer,
        "correct_answer": exercise["correct_answer"],
        "last_seen_at": utc_now(),
        "review_sessions_remaining": 2,
        "resolved": False,
        "retention_successes": 0, "last_correct_at": None,
    }

    if existing.data:
        row = existing.data[0]
        result = (
            supabase.table("learning_errors")
            .update(
                {
                    **payload,
                    "count": int(row.get("count") or 0) + 1,
                }
            )
            .eq("id", row["id"])
            .execute()
        )
    else:
        result = (
            supabase.table("learning_errors")
            .insert(
                {
                    "student_id": student_id,
                    "topic": topic_value,
                    "error_type": exercise["exercise_type"],
                    "count": 1,
                    **payload,
                }
            )
            .execute()
        )

    if not result.data:
        raise RuntimeError(
            "Learning mistake was not saved to Supabase."
        )


def pending_mistakes(student_id: int, limit: int = 10):
    response = (
        supabase.table("learning_errors")
        .select("*")
        .eq("student_id", student_id)
        .eq("resolved", False)
        .gt("review_sessions_remaining", 0)
        .order("last_seen_at", desc=True)
        .limit(limit)
        .execute()
    )
    return response.data or []


def consume_review_mistakes(student_id: int, limit: int = 3):
    """Compatibility helper; opening review does not consume mistakes."""
    return pending_mistakes(student_id, limit)


async def get_next_exercise(
    student_id: int,
    block: str,
    topic: str | None = None,
):
    """Compatibility helper for older callers."""
    exercises = list_exercises(block)
    if not exercises:
        return None

    state = get_student_state(student_id) or {}
    plan = state.get("active_plan") or {}
    index = int(plan.get("index") or 0)

    if index >= len(exercises):
        return None

    return exercises[index]


async def targeted_mistake_exercises(block, topic, originals):
    """Save new, source-grounded practice before rechecking original questions."""
    source = get_lesson(block, topic)
    if not source or not str(source.get('content') or '').strip():
        raise ValueError('Нет материала урока для практики ошибок.')
    focus = '\n'.join(str(row['question']) for row in originals)
    generated = await generate_exercises(block, topic, source['content'], amount=min(3,len(originals)),
        existing_exercises=originals, focus=focus)
    if len(generated)!=min(3,len(originals)):
        raise ValueError('Не удалось подготовить все вопросы для практики.')
    saved_rows=[]
    for item in generated:
        question=_format_generated_question(item)
        answer=str(item.get('correct_answer') or '').strip()
        if not question or not answer: raise ValueError('Вопрос или ответ пустой.')
        result=supabase.table('Exercises').insert(dict(block=block,topic=topic,
            exercise_type=str(item.get('type') or 'practice'),question='[Практика ошибок] '+question,
            correct_answer=answer)).execute().data
        if not result: raise RuntimeError('Вопрос практики не сохранён.')
        AI_EXERCISE_CACHE[result[0]['id']]=result[0]
        saved_rows.append(result[0])
    return saved_rows
